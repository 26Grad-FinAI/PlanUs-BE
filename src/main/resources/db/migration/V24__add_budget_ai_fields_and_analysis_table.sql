ALTER TABLE budget_category ADD COLUMN ai_amount BIGINT NULL;

-- budget 테이블에 AI 총 예산 컬럼 추가
ALTER TABLE budget ADD COLUMN ai_total_budget BIGINT NULL;

-- AI 분석 데이터 별도 저장 테이블
CREATE TABLE budget_plan_analysis (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    budget_id   BIGINT  NOT NULL,
    observation JSONB   NULL,
    persona     JSONB   NULL,
    strategy    JSONB   NULL,
    user_context JSONB  NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_bpa_budget UNIQUE (budget_id),
    CONSTRAINT fk_bpa_budget FOREIGN KEY (budget_id) REFERENCES budget (id)
);
